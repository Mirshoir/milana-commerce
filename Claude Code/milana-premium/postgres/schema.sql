CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE IF NOT EXISTS products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT UNIQUE NOT NULL,
  model_no TEXT NOT NULL DEFAULT '',
  variant TEXT NOT NULL DEFAULT '',
  gender TEXT NOT NULL DEFAULT 'unisex',
  category TEXT NOT NULL,
  catalog_panel TEXT NOT NULL DEFAULT '',
  product_type TEXT NOT NULL DEFAULT '',
  name TEXT NOT NULL,
  desc_en TEXT NOT NULL DEFAULT '',
  desc_ru TEXT NOT NULL DEFAULT '',
  desc_uz TEXT NOT NULL DEFAULT '',
  fabric_en TEXT NOT NULL DEFAULT '',
  fabric_ru TEXT NOT NULL DEFAULT '',
  fabric_uz TEXT NOT NULL DEFAULT '',
  copy_manual BOOLEAN NOT NULL DEFAULT false,
  price NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
  old_price NUMERIC(12, 2),
  sizes JSONB NOT NULL DEFAULT '[]'::jsonb,
  images JSONB NOT NULL DEFAULT '[]'::jsonb,
  tag TEXT NOT NULL DEFAULT '',
  collection TEXT NOT NULL DEFAULT '',
  rating NUMERIC(3, 2) NOT NULL DEFAULT 0,
  reviews INTEGER NOT NULL DEFAULT 0,
  wholesale_price NUMERIC(12, 2) NOT NULL DEFAULT 0,
  wholesale_moq INTEGER NOT NULL DEFAULT 6,
  retail_enabled BOOLEAN NOT NULL DEFAULT true,
  retail_price NUMERIC(12, 2) NOT NULL DEFAULT 0,
  retail_stock INTEGER NOT NULL DEFAULT 0,
  like_count INTEGER NOT NULL DEFAULT 0,
  active BOOLEAN NOT NULL DEFAULT true,
  sort INTEGER NOT NULL DEFAULT 0,
  available_qop INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE products ADD COLUMN IF NOT EXISTS catalog_panel TEXT NOT NULL DEFAULT '';
ALTER TABLE products ADD COLUMN IF NOT EXISTS product_type TEXT NOT NULL DEFAULT '';
ALTER TABLE products ADD COLUMN IF NOT EXISTS collection TEXT NOT NULL DEFAULT '';
ALTER TABLE products ADD COLUMN IF NOT EXISTS copy_manual BOOLEAN NOT NULL DEFAULT false;
CREATE INDEX IF NOT EXISTS idx_products_catalog_panel ON products(active, catalog_panel, sort DESC, id DESC);
UPDATE products
SET catalog_panel = CASE
  WHEN gender = 'men' THEN 'men'
  WHEN gender = 'kids' THEN 'kids'
  WHEN lower(concat_ws(' ', model_no, variant, name, desc_en, desc_ru, desc_uz)) ~ 'халат|xalat|robe|(^| )xj-?[0-9]' OR category = 'robes' THEN 'robes'
  WHEN lower(concat_ws(' ', model_no, variant, name, desc_en, desc_ru, desc_uz)) ~ 'туник|tunika|tunic|(^| )tj-?[0-9]' THEN 'tunics'
  WHEN lower(concat_ws(' ', model_no, variant, name, desc_en, desc_ru, desc_uz)) ~ 'иштон|ishton|штаны|брюки|trousers|pants|(^| )bj-?[0-9]' THEN 'trousers'
  WHEN lower(concat_ws(' ', model_no, variant, name, desc_en, desc_ru, desc_uz)) ~ 'сорочк|sarochka|nightgown|nightdress|кормяшк|(^| )sj-?[0-9]' THEN 'nightgowns'
  WHEN lower(concat_ws(' ', model_no, variant, name, desc_en, desc_ru, desc_uz)) ~ 'двойк|тройк|комплект|dvojka|dvoyka| set |футболк.{0,24}(шорт|бридж|штан)' THEN 'sets'
  WHEN lower(concat_ws(' ', model_no, variant, name, desc_en, desc_ru, desc_uz)) ~ 'футболк|futbolka|t-?shirt|(^| )f-?[0-9]' THEN 'tshirts'
  WHEN category = 'pajamas' OR lower(concat_ws(' ', model_no, variant, name, desc_en, desc_ru, desc_uz)) ~ 'пижам|pijama|pajama|(^| )pj-?[0-9]' THEN 'pajamas'
  ELSE 'sets'
END
WHERE catalog_panel = '';

